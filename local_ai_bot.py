WORD_BASE_SET = set()
WORD_BASE_LIST = []


def strip_punctuation(text):
    translator = str.maketrans("", "", string.punctuation + "«»—…“”")
    return text.translate(translator)


def extract_new_words(user_text):
    cleaned = strip_punctuation(user_text.lower())
    words = cleaned.split()

    known_words = set()
    valid_buckets = (
        "subjects_m", "subjects_f", "subjects_p", "actions", "actions_p",
        "objects", "adj_m", "adj_f", "adj_instr_m", "adverbs", "help_words",
        "user_memory",
    )
    for bucket in valid_buckets:
        if bucket in SEMANTIC_DICT:
            for phrase in SEMANTIC_DICT[bucket]:
                known_words.update(phrase.lower().split())

    new_words = []
    for w in words:
        if len(w) < settings["min_new_word_length"] or w in STOPWORDS_RU or w in known_words or w.isdigit():
            continue
        if w in WORD_BASE_SET:
            continue
        new_words.append(w)

    return list(dict.fromkeys(new_words))


def learn_from_text(user_text):
    if not settings["learning_mode"]:
        return []

    new_words = extract_new_words(user_text)
    if not new_words:
        return []

    for w in new_words:
        if w not in SEMANTIC_DICT["user_memory"]:
            SEMANTIC_DICT["user_memory"].append(w)
        if w not in WORD_BASE_SET:
            WORD_BASE_SET.add(w)
            WORD_BASE_LIST.append(w)

    save_memory_to_disk()
    log(f"Выучено {len(new_words)} новых слов: {', '.join(new_words)}")
    return new_words


def save_memory_to_disk():
    """Сохраняет только слова, изученные из пользовательского диалога (user_memory)."""
    try:
        with open(settings["memory_file"] + ".user", "w", encoding="utf-8") as f:
            for word in SEMANTIC_DICT["user_memory"]:
                f.write(word + "\n")
    except Exception as e:
        log(f"Не удалось сохранить память на диск: {e}")


def load_memory_from_disk():
    """
    Загружает базовую (потенциально миллионную) базу слов в set() для мгновенного
    поиска по содержимому (O(1) на слово) и в список для случайной выборки при
    генерации авто-мыслей.
    """
    global WORD_BASE_SET, WORD_BASE_LIST

    path = settings["memory_file"]
    if os.path.exists(path):
        try:
            with open(path, "r", encoding="utf-8") as f:
                words = {line.strip() for line in f if line.strip()}
            WORD_BASE_SET = words
            WORD_BASE_LIST = list(words)
            log(f"Загружено {len(WORD_BASE_SET)} слов из базовой долговременной памяти в set().")
        except Exception as e:
            log(f"Не удалось загрузить базовую память с диска: {e}")
    else:
        log(f"Файл базовой памяти '{path}' не найден, стартую с пустой базой.")

    user_path = path + ".user"
    if os.path.exists(user_path):
        try:
            with open(user_path, "r", encoding="utf-8") as f:
                user_words = [line.strip() for line in f if line.strip()]
            SEMANTIC_DICT["user_memory"] = list(dict.fromkeys(user_words))
            for w in SEMANTIC_DICT["user_memory"]:
                if w not in WORD_BASE_SET:
                    WORD_BASE_SET.add(w)
                    WORD_BASE_LIST.append(w)
            log(f"Загружено {len(SEMANTIC_DICT['user_memory'])} слов из пользовательской памяти.")
        except Exception as e:
            log(f"Не удалось загрузить пользовательскую память: {e}")


def load_knowledge_base():
    global KNOWLEDGE_BASE
    path = settings.get("kb_file", "knowledge_base.json")
    if os.path.exists(path):
        try:
            with open(path, "r", encoding="utf-8") as f:
                KNOWLEDGE_BASE = json.load(f)
            log(f"Загружено {len(KNOWLEDGE_BASE)} фактов из базы знаний.")
        except Exception as e:
            log(f"Ошибка загрузки базы знаний: {e}")


def save_knowledge_base():
    path = settings.get("kb_file", "knowledge_base.json")
    try:
        with open(path, "w", encoding="utf-8") as f:
            json.dump(KNOWLEDGE_BASE, f, ensure_ascii=False, indent=2)
    except Exception as e:
        log(f"Ошибка сохранения базы знаний: {e}")


def check_teaching_command(user_text):
    """Синтаксис для прямого обучения: 'запомни: вопрос = ответ'"""
    low = user_text.strip()
    if low.lower().startswith("запомни:"):
        payload = low[8:].strip()
        if "=" in payload:
            q, a = payload.split("=", 1)
            q = q.strip().lower()
            a = a.strip()
            if q and a:
                KNOWLEDGE_BASE[q] = a
                save_knowledge_base()
                return f"{emo('status')} Запомнил(а)! На вопрос «{q}» теперь я буду отвечать: «{a}»."
        return f"{emo('error')} Используй формат: запомни: твой вопрос = твой ответ"
    return None


