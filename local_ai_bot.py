def parse_page_headlines(url, max_headlines=10):
    """Извлекает заголовки (h1-h3) со страницы — полезно для новостных лент."""
    try:
        raw = fetch_url(url)
    except Exception as e:
        return f"{emo('error')} Не удалось загрузить страницу: {e}"

    try:
        soup = BeautifulSoup(raw, "html.parser")
    except Exception:
        return f"{emo('error')} Не удалось разобрать содержимое страницы."

    headlines = []
    for tag in soup.find_all(["h1", "h2", "h3"]):
        text = tag.get_text(separator=" ", strip=True)
        if text and len(text) > 5 and text not in headlines:
            headlines.append(text)
        if len(headlines) >= max_headlines:
            break

    if not headlines:
        return f"{emo('error')} На странице не найдено распознаваемых заголовков."

    lines = [f"{emo('search')} Заголовки со страницы {url}:\n"]
    for i, h in enumerate(headlines, start=1):
        lines.append(f"{i}. {h}")
    return "\n".join(lines)


def download_page_content(url):
    """Скачивает текстовое содержимое страницы (абзацы) и сохраняет в локальный файл."""
    try:
        raw = fetch_url(url)
    except Exception as e:
        return f"{emo('error')} Не удалось скачать страницу: {e}"

    try:
        soup = BeautifulSoup(raw, "html.parser")
    except Exception:
        return f"{emo('error')} Не удалось разобрать HTML страницы."

    title_tag = soup.find("title")
    title = title_tag.get_text(strip=True) if title_tag else "Без названия"
    paragraphs = [tag.get_text(separator=" ", strip=True) for tag in soup.find_all("p")]
    paragraphs = [p for p in paragraphs if not is_junk_paragraph(p)]

    downloads_dir = settings["downloads_dir"]
    os.makedirs(downloads_dir, exist_ok=True)

    safe_name = re.sub(r"[^a-zA-Zа-яА-Я0-9]+", "_", title)[:50] or "page"
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    filename = f"{safe_name}_{timestamp}.txt"
    filepath = os.path.join(downloads_dir, filename)

    try:
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(f"URL: {url}\n")
            f.write(f"Заголовок: {title}\n\n")
            f.write("\n\n".join(paragraphs) if paragraphs else "(содержательный текст не найден)")
    except Exception as e:
        return f"{emo('error')} Не удалось сохранить файл: {e}"

    return f"{emo('search')} Страница «{title}» скачана и сохранена в файл: {filepath}"


