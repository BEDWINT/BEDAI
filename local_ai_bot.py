def detect_intent(user_text):
    low = user_text.lower()
    for intent_name, data in INTENTS.items():
        for pattern in data["patterns"]:
            if re.search(pattern, low):
                return intent_name
    return None


def build_response(user_text):
    """
    Строгий приоритет обработки запроса:
      1. Команды/Обучение (запомни:, системные команды, веб-команды открыть/скачать/заголовки)
      2. Математика (уравнения, конвертация единиц, проценты, выражения)
      3. Веб-поиск (найди/погугли/...)
      4. Интенты (приветствия/прощания/эмоции/темы)
      5. Генерация мыслей из базы слов (авто-мысль)
    """
    # --- 1. Команды и обучение ---
    teach_result = check_teaching_command(user_text)
    if teach_result:
        return teach_result

    clean_q = user_text.strip().lower()
    if clean_q in KNOWLEDGE_BASE:
        return f"{KNOWLEDGE_BASE[clean_q]} {emo('status')}"

    web_command_result = try_web_command(user_text)
    if web_command_result:
        return web_command_result

    system_command_result = try_system_command(user_text)
    if system_command_result:
        return system_command_result

    # --- 2. Математика ---
    math_result = solve_math_or_task(user_text)
    if math_result:
        return math_result

    # --- 3. Веб-поиск ---
    if is_search_query(user_text):
        query = clean_search_query(user_text)
        if not query:
            return f"{emo('error')} Уточни, пожалуйста, что именно нужно найти."
        return perform_web_search(query)

    # --- 4. Интенты ---
    intent = detect_intent(user_text)
    learned_words = learn_from_text(user_text)

    if intent:
        base_response = random.choice(INTENTS[intent]["responses"])
        category = INTENT_EMOJI_CATEGORY.get(intent, "neutral")
        base_response += f" {emo(category)}"
        if random.random() < 0.4:
            base_response += " " + generate_semantic_sentence()
        return base_response

    # --- 5. Генерация мысли из базы слов ---
    generated = generate_auto_thought()
    if learned_words:
        generated += f" Кстати, я только что запомнил(а) новое слово: «{learned_words[0]}». {emo('status')}"
    return generated


