NUMBER_BASE_NAMES = {
    "двоичную": 2, "двоичной": 2, "двоичн": 2, "binary": 2,
    "восьмеричную": 8, "восьмеричной": 8, "восьмеричн": 8, "octal": 8,
    "десятичную": 10, "десятичной": 10, "десятичн": 10, "decimal": 10,
    "шестнадцатеричную": 16, "шестнадцатеричной": 16, "шестнадцатер": 16, "hex": 16,
}


def try_convert_number_base(text):
    """
    Распознаёт запросы на перевод числа между системами счисления.
    Пример: "переведи 255 в шестнадцатеричную", "10101 из двоичной в десятичную".
    """
    low = text.lower()

    match_full = re.search(
        r"(\w+)\s+из\s+(\w+)\s+в\s+(\w+)", low
    )
    if match_full:
        number_raw, from_name, to_name = match_full.groups()
        from_base = None
        to_base = None
        for name, base in NUMBER_BASE_NAMES.items():
            if name in from_name:
                from_base = base
            if name in to_name:
                to_base = base
        if from_base and to_base:
            return _do_base_conversion(number_raw, from_base, to_base)

    match_simple = re.search(r"(?:переведи|конвертируй)\s+(\w+)\s+в\s+(\w+)", low)
    if match_simple:
        number_raw, to_name = match_simple.groups()
        to_base = None
        for name, base in NUMBER_BASE_NAMES.items():
            if name in to_name:
                to_base = base
        if to_base:
            return _do_base_conversion(number_raw, 10, to_base)

    return None


def _do_base_conversion(number_raw, from_base, to_base):
    try:
        value = int(number_raw, from_base)
    except ValueError:
        return f"{emo('error')} Число «{number_raw}» некорректно для системы счисления с основанием {from_base}."

    if to_base == 2:
        result = bin(value)[2:]
    elif to_base == 8:
        result = oct(value)[2:]
    elif to_base == 16:
        result = hex(value)[2:].upper()
    else:
        result = str(value)

    base_names = {2: "двоичная", 8: "восьмеричная", 10: "десятичная", 16: "шестнадцатеричная"}
    return (
        f"{emo('math')} Число {number_raw} ({base_names.get(from_base, from_base)}) "
        f"= **{result}** ({base_names.get(to_base, to_base)})"
    )


