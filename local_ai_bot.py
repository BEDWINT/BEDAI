def _convert_temperature(value, from_unit, to_unit):
    from_unit = from_unit.lower()
    to_unit = to_unit.lower()

    if from_unit in ("c", "с", "цельсий", "цельсия"):
        celsius = value
    elif from_unit in ("f", "фаренгейт", "фаренгейту"):
        celsius = (value - 32) * 5 / 9
    elif from_unit in ("k", "кельвин", "кельвину"):
        celsius = value - 273.15
    else:
        raise ValueError("Неизвестная единица температуры.")

    if to_unit in ("c", "с", "цельсий", "цельсия"):
        return celsius
    elif to_unit in ("f", "фаренгейт", "фаренгейту"):
        return celsius * 9 / 5 + 32
    elif to_unit in ("k", "кельвин", "кельвину"):
        return celsius + 273.15
    else:
        raise ValueError("Неизвестная единица температуры.")


def try_convert_units(text):
    """
    Распознаёт запросы на конвертацию единиц измерения.
    Примеры: "переведи 10 км в мили", "100 кг в фунты", "36.6 c в f".
    """
    low = text.lower().replace(",", ".")
    match = re.search(
        r"(\d+\.?\d*)\s*([а-яa-z]+)\s+(?:в|to)\s+([а-яa-z]+)", low
    )
    if not match:
        return None

    value_raw, from_raw, to_raw = match.groups()
    from_key = from_raw.rstrip(".")
    to_key = to_raw.rstrip(".")

    if from_key not in UNIT_ALIASES or to_key not in UNIT_ALIASES:
        return None

    from_category, from_factor = UNIT_ALIASES[from_key]
    to_category, to_factor = UNIT_ALIASES[to_key]

    if from_category != to_category:
        return f"{emo('error')} Нельзя перевести {from_key} в {to_key} — это разные величины."

    value = float(value_raw)

    try:
        if from_category == "temperature":
            result = _convert_temperature(value, from_key, to_key)
        else:
            base_value = value * from_factor
            result = base_value / to_factor
    except ValueError:
        return None
    except ZeroDivisionError:
        return f"{emo('error')} Ошибка конвертации: деление на ноль."

    return f"{emo('math')} {_format_number(value)} {from_raw} = **{_format_number(result)} {to_raw}**"


