_SAFE_BIN_OPS = {
    ast.Add: operator.add,
    ast.Sub: operator.sub,
    ast.Mult: operator.mul,
    ast.Div: operator.truediv,
    ast.Mod: operator.mod,
    ast.Pow: operator.pow,
    ast.FloorDiv: operator.floordiv,
}

_SAFE_UNARY_OPS = {
    ast.USub: operator.neg,
    ast.UAdd: operator.pos,
}


def _safe_eval_ast(node):
    """Рекурсивно и безопасно вычисляет узел AST-дерева математического выражения."""
    if isinstance(node, ast.Expression):
        return _safe_eval_ast(node.body)

    if isinstance(node, ast.Constant):
        if isinstance(node.value, (int, float)):
            return node.value
        raise ValueError("В выражении встречена недопустимая константа.")

    if isinstance(node, ast.BinOp):
        op_type = type(node.op)
        if op_type not in _SAFE_BIN_OPS:
            raise ValueError("Такой оператор не поддерживается.")
        left = _safe_eval_ast(node.left)
        right = _safe_eval_ast(node.right)
        if op_type is ast.Pow and (abs(right) > 1000 or abs(left) > 10 ** 6):
            raise ValueError("Слишком большая степень для безопасного вычисления.")
        if op_type in (ast.Div, ast.FloorDiv, ast.Mod) and right == 0:
            raise ZeroDivisionError("Деление на ноль недопустимо.")
        return _SAFE_BIN_OPS[op_type](left, right)

    if isinstance(node, ast.UnaryOp):
        op_type = type(node.op)
        if op_type not in _SAFE_UNARY_OPS:
            raise ValueError("Такой унарный оператор не поддерживается.")
        return _SAFE_UNARY_OPS[op_type](_safe_eval_ast(node.operand))

    raise ValueError("Обнаружена недопустимая конструкция в выражении.")


def safe_calculate(expression):
    """
    Безопасно вычисляет арифметическое выражение (без eval/exec и без builtins).
    Поддерживает + - * / // % ** и скобки. Бросает понятные исключения при ошибках.
    """
    normalized = expression.replace(",", ".").replace("^", "**").replace("х", "*").replace("÷", "/")
    normalized = normalized.strip()
    if not normalized:
        raise ValueError("Пустое выражение.")

    tree = ast.parse(normalized, mode="eval")
    return _safe_eval_ast(tree.body if hasattr(tree, "body") else tree)


def try_solve_expression(text):
    """Пытается вычленить и решить арифметическое выражение из свободного текста."""
    working = text.lower()
    working = working.replace("плюс", "+").replace("минус", "-")
    working = working.replace("умножить на", "*").replace("умножить", "*")
    working = working.replace("разделить на", "/").replace("разделить", "/")
    working = working.replace("в степени", "**")

    sqrt_match = re.search(r"корень\s+из\s+(-?\d+[.,]?\d*)", working)
    if sqrt_match:
        try:
            value = float(sqrt_match.group(1).replace(",", "."))
            if value < 0:
                return f"{emo('error')} Квадратный корень из отрицательного числа не определён на множестве действительных чисел."
            result = value ** 0.5
            result_str = _format_number(result)
            return f"{emo('math')} Квадратный корень из {_format_number(value)} = **{result_str}**"
        except Exception:
            pass

    clean_expr = re.sub(r"[^0-9+\-*/().]", "", working)
    if not clean_expr or not any(op in clean_expr for op in ("+", "-", "*", "/")):
        return None

    if not re.search(r"\d", clean_expr):
        return None

    try:
        result = safe_calculate(clean_expr)
        result_str = _format_number(result)
        return f"{emo('math')} Решение примера:\n`{clean_expr}` = **{result_str}**"
    except ZeroDivisionError:
        return f"{emo('error')} На ноль делить нельзя — выражение `{clean_expr}` не имеет решения."
    except (ValueError, SyntaxError, TypeError, OverflowError):
        return f"{emo('error')} Не смог(ла) безопасно вычислить это выражение, проверь синтаксис примера."
    except Exception:
        return f"{emo('error')} Что-то пошло не так при вычислении, попробуй переформулировать пример."


def _format_number(value):
    """Форматирует число: убирает лишние нули у float, если результат целый."""
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    if isinstance(value, float):
        return f"{round(value, 6):g}"
    return str(value)


def _coef_to_float(raw):
    raw = raw.replace(" ", "")
    if raw in ("", "+"):
        return 1.0
    if raw == "-":
        return -1.0
    return float(raw.replace(",", "."))


def try_solve_quadratic(text):
    """
    Распознаёт и решает квадратные уравнения вида ax^2+bx+c=0.
    Устойчив к отсутствующим слагаемым: "2x^2+3x-5=0", "x^2-4=0",
    "x^2+2x+1=0", "3x^2=0" и т.п.
    """
    low = text.lower().replace(" ", "").replace(",", ".")
    if "x" not in low or "=0" not in low:
        return None

    left = low.split("=0")[0]
    if not left or "x" not in left:
        return None

    a_match = re.search(r"([+-]?\d*\.?\d*)x\^?2", left)
    if not a_match:
        return None

    a_raw = a_match.group(1)
    remainder = left[:a_match.start()] + left[a_match.end():]

    b_match = re.search(r"([+-]?\d*\.?\d*)x(?!\^?2)", remainder)
    if b_match:
        b_raw = b_match.group(1)
        remainder2 = remainder[:b_match.start()] + remainder[b_match.end():]
    else:
        b_raw = "0"
        remainder2 = remainder

    c_raw = remainder2.strip() or "0"

    try:
        a = _coef_to_float(a_raw)
        b = _coef_to_float(b_raw)
        c = _coef_to_float(c_raw)
    except ValueError:
        return f"{emo('error')} Не удалось распознать коэффициенты квадратного уравнения."

    if a == 0:
        return f"{emo('error')} Коэффициент при x² не может быть равен нулю в квадратном уравнении."

    discriminant = b ** 2 - 4 * a * c
    header = f"{emo('math')} Квадратное уравнение: {_format_number(a)}x² + ({_format_number(b)})x + ({_format_number(c)}) = 0\n"
    header += f"Дискриминант D = {_format_number(discriminant)}\n"

    if discriminant > 0:
        x1 = (-b + discriminant ** 0.5) / (2 * a)
        x2 = (-b - discriminant ** 0.5) / (2 * a)
        return header + f"Два корня: **x1 = {_format_number(x1)}**, **x2 = {_format_number(x2)}**"
    elif discriminant == 0:
        x1 = -b / (2 * a)
        return header + f"Один корень (кратный): **x = {_format_number(x1)}**"
    else:
        real = -b / (2 * a)
        imag = (abs(discriminant) ** 0.5) / (2 * a)
        return header + (
            f"Действительных корней нет. Комплексные корни: "
            f"**x1 = {_format_number(real)} + {_format_number(imag)}i**, "
            f"**x2 = {_format_number(real)} - {_format_number(imag)}i**"
        )


def try_solve_percentage(text):
    """Распознаёт и решает процентные задачи."""
    low = text.lower().replace(",", ".")

    match = re.search(r"(\d+\.?\d*)\s*%\s*от\s*(\d+\.?\d*)", low)
    if match:
        percent = float(match.group(1))
        base = float(match.group(2))
        result = base * percent / 100
        return f"{emo('math')} {_format_number(percent)}% от {_format_number(base)} = **{_format_number(result)}**"

    match = re.search(r"(увеличь|прибавь)\s*(\d+\.?\d*)\s*на\s*(\d+\.?\d*)\s*%", low)
    if match:
        base = float(match.group(2))
        percent = float(match.group(3))
        result = base * (1 + percent / 100)
        return f"{emo('math')} {_format_number(base)} увеличено на {_format_number(percent)}% = **{_format_number(result)}**"

    match = re.search(r"(уменьши|отними)\s*(\d+\.?\d*)\s*на\s*(\d+\.?\d*)\s*%", low)
    if match:
        base = float(match.group(2))
        percent = float(match.group(3))
        result = base * (1 - percent / 100)
        return f"{emo('math')} {_format_number(base)} уменьшено на {_format_number(percent)}% = **{_format_number(result)}**"

    match = re.search(r"сколько\s+процентов\s+(\d+\.?\d*)\s+от\s+(\d+\.?\d*)", low)
    if match:
        part = float(match.group(1))
        whole = float(match.group(2))
        if whole == 0:
            return f"{emo('error')} Нельзя делить на ноль при расчёте процента."
        result = part / whole * 100
        return f"{emo('math')} {_format_number(part)} составляет **{_format_number(result)}%** от {_format_number(whole)}"

    return None


