    """
    Единый диспетчер системных команд.
    Проверяет: дата/время -> инфо о ПК -> пароль -> валюта -> система счисления.
    Возвращает None, если ни одна системная команда не распознана.
    """
    low = text.lower()

    if re.search(r"\bсколько\s+времени\b|\bкоторый\s+час\b|\bкакая\s+дата\b|\bкакое\s+сегодня\s+число\b|\bкакой\s+сегодня\s+день\b", low):
        return get_datetime_info()

    if re.search(r"\bинформация\s+о\s+(пк|компьютере|системе)\b|\bнагрузка\s+(cpu|проц|процессора)\b|\bзагрузка\s+(системы|озу|памяти)\b|\bсостояние\s+системы\b", low):
        return get_system_info()

    password_result = try_generate_password_command(text)
    if password_result:
        return password_result

    number_base_result = try_convert_number_base(text)
    if number_base_result:
        return number_base_result

    currency_result = try_currency_command(text)
    if currency_result:
        return currency_result

    return None


